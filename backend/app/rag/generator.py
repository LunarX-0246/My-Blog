"""生成与引用（技术方案 §6.8，红线 R1）。

System Prompt 硬约束：只基于检索内容作答，严禁用模型通用知识补充。
注意：**不要**写「若资料未提及可结合通用知识」——这与本项目核心设计相悖
（访客若得到的是通用模型回答而非博主观点，本功能相对直接使用 DeepSeek 就无意义）。
"""

SYSTEM_PROMPT = (
    "你是「My Blog」的问答助手，只根据下面提供的「参考资料」回答。\n\n"
    "严格遵守：\n"
    "1. 只使用「参考资料」中的内容作答，禁止使用你自己的通用知识补充或推测。\n"
    "2. 每个关键论断后标注来源编号，如 [1]、[2]。\n"
    "3. 如果参考资料不足以回答，直接说明「知识库中没有相关内容」，"
    "并推荐资料中最接近的 2-3 项，绝不编造。\n"
    "4. 保持与博客一致的语气与术语。"
)


def build_context(sources: list) -> str:
    """把检索结果组装为「参考资料」，每条编号 [n]。"""
    blocks = []
    for i, s in enumerate(sources, 1):
        blocks.append(f"[{i}] {s.context_prefix}\n{s.content}")
    return "\n\n".join(blocks)
